/// <summary>
/// Deterministic coverage for the last window in which a Presentation Studio result can
/// still change: the final PPTX publish callback.
///
/// The existing cancellation work settles the question strictly upstream of that window.
/// #1013/#1051 cancel the caller token while the provider response is in flight, so
/// <c>AiPresentationGenerationProvider</c> re-asserts and the attempt never reaches
/// parse/validate/render; their <c>PresentationCancellationLedgerApiTests</c> proves the
/// durable terminal state from that same provider-boundary interleaving, and their
/// renderer counter stays at zero precisely because publication is never entered. #1020
/// settles the handler's own late failure boundaries (draft parse, validation, render,
/// output integrity). Nothing in #1051, #1020, #1013 or #1080 - and nothing on main -
/// drives a cancellation into the case where the deck has ALREADY finished and the asset
/// publication for that finished file is still open.
///
/// This file pins that case. Here the handler returns a validated, rendered, publishable
/// artifact, the worker passes its pre-publication re-check, and the user's durable
/// cancellation is recorded while <c>IGeneratedAssetPublisher.PrepareAsync</c> - the
/// callback that hands the finished PPTX over for publication - is deliberately delayed.
/// The interleaving is imposed by a gate on the callback, not by timing, so the outcome is
/// decided by exactly one predicate: the completion UPDATE only accepts a finished result
/// while the job row still reads <c>Status == Running</c>, the claim's
/// <c>ConcurrencyToken</c> and <c>!CancellationRequested</c>.
///
/// Asserted behaviour:
/// 1. Cancellation wins: the attempt settles as Cancelled with the cancellation code and
///    never transitions to a completed state - no <c>CompletedAt</c>, no <c>ResultJson</c>.
/// 2. The finished deck never becomes downloadable: no <see cref="GenerationJobOutput"/>
///    row, no <see cref="Asset"/> row, the read model exposes no outputs, the prepared
///    asset is refused by the download surface, and the prepared publication is withdrawn
///    through <c>DiscardAsync</c> exactly once.
/// 3. Repeated cancellation is idempotent: it stays a sticky accepted intent while the
///    callback is open without re-running the attempt, is refused once the attempt has
///    settled, and never changes the settled terminal state, the discard count or the
///    usage ledger.
///
/// No provider is contacted and no storage is written: the provider and the asset
/// publisher are both scripted in-memory doubles, the deck and its publication are
/// synthetic, no credentials or private data are read, no customer is charged, and no real
/// file is published. Only bounded observation loops are used, and each one fails fast
/// with a diagnostic if the state it waits for cannot arrive.
/// </summary>
public sealed class PresentationPublicationCancellationApiFactory : GenerationJobsApiFactory
{
    /// <summary>
    /// The scripted final PPTX publish callback. The worker resolves it inside its own
    /// execution scope, so this single gated instance is the one that holds the finished
    /// deck's publication open for the cancellation to land behind.
    /// </summary>
    public DelayedPublicationAssetPublisher Publisher { get; } = new();

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        base.ConfigureWebHost(builder);
        builder.UseSetting("PresentationGeneration:Enabled", "true");
        builder.UseSetting("PresentationGeneration:ProviderTimeoutSeconds", "30");
        builder.ConfigureServices(services =>
        {
            // The attempt must genuinely succeed - provider, validation, rendering and
            // integrity all pass - otherwise it settles before publication and proves
            // nothing about this window. Only the asset publication itself is scripted,
            // which is also what keeps every generated byte out of real storage.
            services.RemoveAll<IPresentationGenerationProvider>();
            services.AddSingleton<IPresentationGenerationProvider, FinishedDeckPresentationProvider>();
            services.RemoveAll<IGeneratedAssetPublisher>();
            services.AddSingleton<IGeneratedAssetPublisher>(Publisher);
        });
    }
}

public sealed class PresentationPublicationCancellationRaceTests : IClassFixture<PresentationPublicationCancellationApiFactory>
{
    private readonly PresentationPublicationCancellationApiFactory factory;

    public PresentationPublicationCancellationRaceTests(PresentationPublicationCancellationApiFactory factory)
    {
        this.factory = factory;
        using var scope = factory.Services.CreateScope();
        scope.ServiceProvider.GetRequiredService<TaslimDbContext>().Database.EnsureCreated();
    }

    [Fact]
    public async Task Cancellation_recorded_while_the_final_pptx_publish_callback_is_delayed_never_completes_the_job_or_publishes_the_result()
    {
        factory.Publisher.ResetGate();
        using var client = factory.CreateClient();
        var workspaceId = await RegisterAsync(client);
        var jobId = await CreatePresentationJobAsync(client, workspaceId);

        // The finished deck has reached the publish callback, so the worker has already
        // passed its pre-publication re-check: this is the last window in which a
        // completed result could still be committed.
        await WaitForPublicationEnteredAsync(jobId);
        Assert.Equal(1, factory.Publisher.PrepareCallCount);

        var beforeCancel = await ReadJobAsync(jobId);
        Assert.Equal(GenerationJobStatus.Running, beforeCancel.Status);
        Assert.False(beforeCancel.CancellationRequested);
        Assert.Null(beforeCancel.CancelledAt);
        Assert.Null(beforeCancel.CompletedAt);

        var cancel = await CancelAsync(client, jobId);
        Assert.Equal(HttpStatusCode.Accepted, cancel.StatusCode);

        // The intent is durable while the callback is still open, and nothing has settled
        // early: the interleaving under test is the one that is actually in force.
        var duringCallback = await ReadJobAsync(jobId);
        Assert.True(duringCallback.CancellationRequested);
        Assert.Equal(GenerationJobStatus.Running, duringCallback.Status);
        Assert.Null(duringCallback.CancelledAt);
        Assert.Null(duringCallback.CompletedAt);

        // The delayed callback now completes with the finished, publishable deck.
        factory.Publisher.ReleasePublication();
        var terminal = await WaitForTerminalAsync(jobId);

        // 1. Cancellation wins over the completed result.
        Assert.Equal(GenerationJobStatus.Cancelled, terminal.Status);
        Assert.Equal(GenerationJobErrorCodes.PresentationCancelled, terminal.ErrorCode);
        Assert.NotNull(terminal.CancelledAt);
        Assert.Null(terminal.CompletedAt);
        Assert.Null(terminal.FailedAt);
        Assert.Null(terminal.ResultJson);

        // 2. Nothing the Studio could turn into a download survived the cancellation.
        Assert.Equal(0, await CountOutputsAsync(jobId));
        Assert.Equal(0, await CountAssetsAsync(jobId));
        Assert.NotNull(factory.Publisher.PreparedAssetId);
        Assert.False(await AssetRowExistsAsync(factory.Publisher.PreparedAssetId!.Value));

        // The publication the callback had prepared is explicitly withdrawn, once, and the
        // attempt is never re-published.
        Assert.Equal(1, factory.Publisher.PrepareCallCount);
        Assert.Equal(1, factory.Publisher.DiscardCallCount);

        var readModel = await client.GetFromJsonAsync<GenerationJobDto>($"/api/generation/jobs/{jobId}");
        Assert.NotNull(readModel);
        Assert.Equal("Cancelled", readModel!.Status);
        Assert.Null(readModel.ResultJson);
        Assert.Empty(readModel.Outputs);

        // And the download surface refuses the deck the delayed callback prepared.
        var download = await client.GetAsync($"/api/assets/{factory.Publisher.PreparedAssetId!.Value}/download");
        Assert.Equal(HttpStatusCode.NotFound, download.StatusCode);
        var downloadBody = await download.Content.ReadFromJsonAsync<JsonElement>();
        Assert.Equal("ASSET_NOT_FOUND", downloadBody.GetProperty("error").GetProperty("code").GetString());

        // The spend reservation settles as a cancellation, never as a completed charge.
        var usage = await ReadUsageAsync(jobId);
        Assert.Equal(UsageTransactionStatus.Cancelled, usage.Status);
        Assert.Equal(0m, usage.ChargedAmount);
        Assert.Equal(0m, usage.ProviderCostUsd);
        Assert.False(usage.IsBillable);
        Assert.Equal(GenerationJobErrorCodes.PresentationCancelled, usage.FailureCode);
    }

    [Fact]
    public async Task Repeated_cancellation_of_a_presentation_job_is_idempotent_across_the_publish_callback_and_after_it_settles()
    {
        factory.Publisher.ResetGate();
        using var client = factory.CreateClient();
        var workspaceId = await RegisterAsync(client);
        var jobId = await CreatePresentationJobAsync(client, workspaceId);

        await WaitForPublicationEnteredAsync(jobId);

        var first = await CancelAsync(client, jobId);
        Assert.Equal(HttpStatusCode.Accepted, first.StatusCode);

        // Repeating the cancellation while the publish callback is still open records the
        // same intent again; it must not re-run the attempt or publish anything.
        var second = await CancelAsync(client, jobId);
        Assert.Equal(HttpStatusCode.Accepted, second.StatusCode);
        var third = await CancelAsync(client, jobId);
        Assert.Equal(HttpStatusCode.Accepted, third.StatusCode);

        var beforeRelease = await ReadJobAsync(jobId);
        Assert.True(beforeRelease.CancellationRequested);
        Assert.Equal(GenerationJobStatus.Running, beforeRelease.Status);
        Assert.Null(beforeRelease.CancelledAt);
        Assert.Equal(1, factory.Publisher.PrepareCallCount);
        Assert.Equal(0, factory.Publisher.DiscardCallCount);
        Assert.Equal(0, await CountOutputsAsync(jobId));
        Assert.Equal(0, await CountAssetsAsync(jobId));

        factory.Publisher.ReleasePublication();
        var terminal = await WaitForTerminalAsync(jobId);
        Assert.Equal(GenerationJobStatus.Cancelled, terminal.Status);
        var settledCancelledAt = terminal.CancelledAt;
        Assert.NotNull(settledCancelledAt);

        // Once the attempt has settled, a further cancellation is refused instead of being
        // re-applied, so it cannot re-open the window or finalize anything twice.
        var afterSettle = await CancelAsync(client, jobId);
        Assert.Equal(HttpStatusCode.Conflict, afterSettle.StatusCode);
        var afterSettleBody = await afterSettle.Content.ReadFromJsonAsync<JsonElement>();
        Assert.Equal(GenerationJobErrorCodes.NotCancellable, afterSettleBody.GetProperty("error").GetProperty("code").GetString());

        var repeatedAfterSettle = await CancelAsync(client, jobId);
        Assert.Equal(HttpStatusCode.Conflict, repeatedAfterSettle.StatusCode);

        // The settled terminal state is byte-for-byte unchanged by the rejected repeats.
        var unchanged = await ReadJobAsync(jobId);
        Assert.Equal(GenerationJobStatus.Cancelled, unchanged.Status);
        Assert.Equal(GenerationJobErrorCodes.PresentationCancelled, unchanged.ErrorCode);
        Assert.Equal(settledCancelledAt, unchanged.CancelledAt);
        Assert.Null(unchanged.CompletedAt);
        Assert.Null(unchanged.ResultJson);
        Assert.Equal(0, await CountOutputsAsync(jobId));
        Assert.Equal(0, await CountAssetsAsync(jobId));
        Assert.Equal(1, factory.Publisher.PrepareCallCount);
        Assert.Equal(1, factory.Publisher.DiscardCallCount);

        var usage = await ReadUsageAsync(jobId);
        Assert.Equal(UsageTransactionStatus.Cancelled, usage.Status);
        Assert.Equal(0m, usage.ChargedAmount);
        Assert.False(usage.IsBillable);
    }

    // The bounded loops below only observe a state the gates already decided; they fail
    // fast with a diagnostic instead of silently waiting on an outcome that cannot arrive.
    private async Task WaitForPublicationEnteredAsync(Guid jobId)
    {
        for (var attempt = 0; attempt < 600; attempt++)
        {
            if (factory.Publisher.PublicationEntered.IsCompleted)
            {
                Assert.Equal(jobId, factory.Publisher.PreparedJobId);
                return;
            }

            var settled = await ReadJobAsync(jobId);
            Assert.True(
                settled.Status != GenerationJobStatus.Failed && settled.Status != GenerationJobStatus.Succeeded,
                $"Presentation attempt settled as {settled.Status} ({settled.ErrorCode}: {settled.ErrorMessage}) before the publish callback opened.");
            await Task.Delay(10);
        }

        throw new TimeoutException($"The final PPTX publish callback was never entered for job {jobId}.");
    }

    private async Task<GenerationJob> WaitForTerminalAsync(Guid jobId)
    {
        for (var attempt = 0; attempt < 1_200; attempt++)
        {
            var job = await ReadJobAsync(jobId);
            if (job.Status is GenerationJobStatus.Succeeded or GenerationJobStatus.Failed or GenerationJobStatus.Cancelled) return job;
            await Task.Delay(10);
        }

        throw new TimeoutException($"Presentation job {jobId} never reached a terminal state.");
    }

    private async Task<GenerationJob> ReadJobAsync(Guid jobId)
    {
        using var scope = factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<TaslimDbContext>();
        return await db.GenerationJobs.AsNoTracking().SingleAsync(item => item.Id == jobId);
    }

    private async Task<int> CountOutputsAsync(Guid jobId)
    {
        using var scope = factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<TaslimDbContext>();
        return await db.GenerationJobOutputs.CountAsync(item => item.GenerationJobId == jobId);
    }

    private async Task<int> CountAssetsAsync(Guid jobId)
    {
        using var scope = factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<TaslimDbContext>();
        return await db.Assets.CountAsync(item => item.SourceGenerationJobId == jobId);
    }

    private async Task<bool> AssetRowExistsAsync(Guid assetId)
    {
        using var scope = factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<TaslimDbContext>();
        return await db.Assets.AsNoTracking().AnyAsync(item => item.Id == assetId);
    }

    private async Task<UsageTransaction> ReadUsageAsync(Guid jobId)
    {
        using var scope = factory.Services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<TaslimDbContext>();
        return await db.UsageTransactions.AsNoTracking().SingleAsync(item => item.GenerationJobId == jobId);
    }

    private static async Task<Guid> RegisterAsync(HttpClient client)
    {
        var csrf = await client.GetFromJsonAsync<JsonElement>("/api/auth/csrf");
        using var request = new HttpRequestMessage(HttpMethod.Post, "/api/auth/register");
        request.Headers.Add("X-CSRF-TOKEN", csrf.GetProperty("token").GetString()!);
        request.Content = JsonContent.Create(new
        {
            displayName = "Publication Race Tester",
            email = $"publication-cancel-race-{Guid.NewGuid():N}@example.com",
            password = "StrongPassword!123",
            preferredLanguage = "en",
        });
        var response = await client.SendAsync(request);
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var auth = (await response.Content.ReadFromJsonAsync<AuthResponse>())!;
        return auth.PersonalWorkspace.Id;
    }

    private static async Task<Guid> CreatePresentationJobAsync(HttpClient client, Guid workspaceId)
    {
        var csrf = await client.GetFromJsonAsync<JsonElement>("/api/auth/csrf");
        using var request = new HttpRequestMessage(HttpMethod.Post, "/api/presentation-generation/jobs");
        request.Headers.Add("X-CSRF-TOKEN", csrf.GetProperty("token").GetString()!);
        request.Headers.Add("Idempotency-Key", $"publication-cancel-race-{Guid.NewGuid():N}");
        request.Content = JsonContent.Create(new
        {
            workspaceId,
            title = "Launch plan",
            description = "Present the launch plan to the operating team.",
            presentationType = "business",
            length = "standard",
            tone = "professional",
            language = "en",
            includeAgenda = true,
            includeClosingNextSteps = true,
            attachmentIds = Array.Empty<Guid>(),
        });
        var response = await client.SendAsync(request);
        Assert.Equal(HttpStatusCode.Accepted, response.StatusCode);
        var created = (await response.Content.ReadFromJsonAsync<CreatePresentationGenerationResponse>())!;
        return created.Job.Id;
    }

    private static async Task<HttpResponseMessage> CancelAsync(HttpClient client, Guid jobId)
    {
        var csrf = await client.GetFromJsonAsync<JsonElement>("/api/auth/csrf");
        using var request = new HttpRequestMessage(HttpMethod.Post, $"/api/generation/jobs/{jobId}/cancel");
        request.Headers.Add("X-CSRF-TOKEN", csrf.GetProperty("token").GetString()!);
        request.Content = JsonContent.Create(new { });
        return await client.SendAsync(request);
    }
}

/// <summary>
/// Stands in for <c>GeneratedAssetPublisher</c> for the final PPTX hand-off. The prepared
/// publication is complete enough that the completion UPDATE could commit a real,
/// downloadable deck - a job output plus an asset carrying the rendered pptx descriptor -
/// while the callback itself is held open on an explicit gate so a cancellation can be
/// recorded strictly inside the window. The callback deliberately does not observe the
/// caller's cancellation token: a publication already in flight is exactly the adversarial
/// case, and the durable cancellation predicate is what has to win. No byte is written to
/// storage, which is what keeps this a provider- and storage-free test.
/// </summary>
public sealed class DelayedPublicationAssetPublisher : IGeneratedAssetPublisher
{
    private TaskCompletionSource<bool> publicationEntered = NewGate();
    private TaskCompletionSource<bool> publicationRelease = NewGate();

    public Task<bool> PublicationEntered => publicationEntered.Task;
    public Guid? PreparedJobId { get; private set; }
    public Guid? PreparedAssetId { get; private set; }
    public int PrepareCallCount { get; private set; }
    public int DiscardCallCount { get; private set; }

    public void ResetGate()
    {
        publicationEntered = NewGate();
        publicationRelease = NewGate();
        PreparedJobId = null;
        PreparedAssetId = null;
        PrepareCallCount = 0;
        DiscardCallCount = 0;
    }

    public void ReleasePublication() => publicationRelease.TrySetResult(true);

    public async Task<PreparedGenerationOutput> PrepareAsync(GenerationJob job, GenerationHandlerOutput output, CancellationToken cancellationToken = default)
    {
        PrepareCallCount += 1;
        PreparedJobId = job.Id;
        var prepared = Build(job, output);
        PreparedAssetId = prepared.Asset!.Id;
        publicationEntered.TrySetResult(true);
        await publicationRelease.Task;
        return prepared;
    }

    public Task DiscardAsync(PreparedGenerationOutput publication, CancellationToken cancellationToken = default)
    {
        DiscardCallCount += 1;
        return Task.CompletedTask;
    }

    private static PreparedGenerationOutput Build(GenerationJob job, GenerationHandlerOutput output)
    {
        var now = DateTime.UtcNow;
        var descriptor = output.Asset;
        var artifact = output.FileArtifact;
        var asset = new Asset
        {
            Id = Guid.NewGuid(),
            WorkspaceId = job.WorkspaceId,
            ProjectId = job.ProjectId,
            CreatedByUserId = job.CreatedByUserId,
            SourceGenerationJobId = job.Id,
            Name = string.IsNullOrWhiteSpace(descriptor?.Name) ? "Launch plan" : descriptor!.Name,
            Description = descriptor?.Description,
            AssetType = descriptor?.AssetType ?? AssetTypes.Presentation,
            MimeType = artifact?.ContentType,
            MetadataJson = descriptor?.MetadataJson ?? output.MetadataJson,
            CreatedAt = now,
            UpdatedAt = now,
        };
        var jobOutput = new GenerationJobOutput
        {
            Id = Guid.NewGuid(),
            GenerationJobId = job.Id,
            StoredFileId = output.StoredFileId,
            OutputType = output.OutputType,
            MetadataJson = output.MetadataJson,
            CreatedAt = now,
        };
        // Provenance is left null on purpose: the retention hook is another storage
        // collaborator, and this race is decided by the completion predicate alone.
        return new PreparedGenerationOutput(jobOutput, asset, null, null);
    }

    private static TaskCompletionSource<bool> NewGate() => new(TaskCreationOptions.RunContinuationsAsynchronously);
}

/// <summary>
/// A provider whose attempt succeeds outright, so the job really does reach publication
/// instead of settling at an earlier boundary. Synthetic and flagged as a test response:
/// no provider is contacted, configured or activated, and no customer is charged.
/// </summary>
public sealed class FinishedDeckPresentationProvider : IPresentationGenerationProvider
{
    public Task<PresentationProviderResult> GenerateAsync(PresentationGenerationPrompt prompt, PresentationGenerationOptions options, CancellationToken cancellationToken = default)
    {
        var draft = new PresentationDraft
        {
            Title = "Launch plan",
            Subtitle = "Quarterly review",
            Language = "en",
            Theme = "professional-navy",
            PresentationType = "business",
            Slides =
            [
                new PresentationSlide
                {
                    Order = 1,
                    Type = PresentationSlideTypes.Title,
                    Title = "Launch plan",
                    Subtitle = "Quarterly review",
                },
                new PresentationSlide
                {
                    Order = 2,
                    Type = PresentationSlideTypes.Bullets,
                    Title = "Operating priorities",
                    Blocks = [new PresentationContentBlock { Type = PresentationBlockTypes.Bullets, Items = ["Ship the release", "Review adoption"] }],
                },
            ],
        };
        var usage = new Taslim.Api.Ai.AiUsageMetadata("presentation-publication-race", "presentation-publication-race-model", 100, null, 200, 0.002m, 0.002m, 8, "completed", true);
        return Task.FromResult(new PresentationProviderResult(draft, usage));
    }
}
