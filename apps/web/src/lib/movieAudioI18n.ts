const numberLocales: Record<Locale, string> = {
  en: "en-US",
  ar: "ar-u-nu-arab",
  ku: "ku-Arab-u-nu-arab",
};

export function movieAudioText(
  locale: Locale,
  key: MovieAudioKey,
  variables: Record<string, string | number> = {},
) {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_, variable: string) =>
    String(variables[variable] ?? `{${variable}}`),
  );
}

export function movieAudioStatusLabel(locale: Locale, value: string) {
  return statusLabels[locale][value as AudioStatus] ?? value;
}

export function formatMovieAudioNumber(locale: Locale, value: number) {
  return new Intl.NumberFormat(numberLocales[locale], {
    maximumFractionDigits: 2,
  }).format(value);
}
