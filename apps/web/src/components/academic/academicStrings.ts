/**
 * The complete English key set. `ar` and `ku` are typed against it, so a key
 * cannot be added to a component without existing here.
 */
export type AcademicStringKey = keyof typeof en | keyof typeof enCopy | keyof typeof enStatus;

const dictionaries: Record<string, Partial<Record<AcademicStringKey, string>>> = { en: { ...en, ...enCopy, ...enStatus }, ar, ku };

/** Interpolates `{name}` placeholders without regex rebuilding per call. */
function interpolate(value: string, variables?: Record<string, string>): string {
  if (!variables) return value;
  let out = value;
  for (const [name, replacement] of Object.entries(variables)) out = out.split(`{${name}}`).join(replacement);
  return out;
}

export type AcademicTranslate = (key: AcademicStringKey, variables?: Record<string, string>) => string;

/**
 * Casts a computed key (a validation message id, a source-type flag) into the
 * dictionary key space. Every such key is produced by the domain modules in this
 * folder, and the tests assert that the dictionary answers them all.
 */
export function asKey(key: string): AcademicStringKey {
  return key as AcademicStringKey;
}

/**
 * Per-key fallback translator: a missing Arabic or Kurdish string resolves to
 * English rather than rendering the raw key, mirroring the shared translator.
 */
export function createAcademicTranslator(locale: string): AcademicTranslate {
  const active = dictionaries[locale] ?? dictionaries.en;
  const english = dictionaries.en;
  return (key, variables) => interpolate(active[key] ?? english[key] ?? String(key), variables);
}

/** Keys of the dictionary, for coverage tests. */
export function academicStringKeys(): string[] {
  return Object.keys(dictionaries.en);
}

/** How many keys a locale covers, for the language-pack follow-up. */
export function academicLocaleCoverage(locale: "en" | "ar" | "ku"): number {
  const dictionary = dictionaries[locale] ?? {};
  return Object.keys(dictionary).filter((key) => key in dictionaries.en).length;
}

export type AcademicLabelers = {
  discipline: (id: string) => string;
  level: (level: "masters" | "doctoral") => string;
  style: (style: CitationStyleId) => string;
  methodology: (methodology: (typeof methodologyOptions)[number]) => string;
  sourceType: (type: AcademicSourceType) => string;
  access: (level: AccessLevel) => string;
};

/**
 * Option labels for the domain catalogues. Panels stay presentational and the
 * copy lives only in this file.
 */
export function createAcademicLabels(t: AcademicTranslate): AcademicLabelers {
  return {
    discipline: (id) => t(asKey(findDiscipline(id).labelKey)),
    level: (level) => t(asKey(`level.${level}`)),
    style: (style) => t(asKey(`style.${style}`)),
    methodology: (methodology) => t(asKey(`methodology.${methodology}`)),
    sourceType: (type) => t(asKey(`sourceType.${type}`)),
    access: (level) => t(asKey(`access.${level}`)),
  };
}

